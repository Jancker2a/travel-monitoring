class ComprehensiveCatalogQARunner:
    def __init__(self, base_url: str = "http://localhost:8088"):
        self.base_url = base_url
        self.results = []
        self.bugs_found = []

    def record_result(self, test_id: str, title: str, passed: bool, details: str = ""):
        self.results.append({
            "test_id": test_id,
            "title": title,
            "passed": passed,
            "details": details,
        })
        status_str = "✅ PASS" if passed else "❌ FAIL"
        print(f"[{status_str}] {test_id}: {title}")
        if not passed:
            self.bugs_found.append(f"{test_id}: {title} -> {details}")
            print(f"   ⚠️ BUG: {details}")

    # ==========================================
    # SUITE 1: DATA INTEGRITY & BUSINESS RULES
    # ==========================================
    def run_suite_1_data_integrity(self):
        print("\n--- Running Suite 1: Data Integrity & Business Rules ---")

        # TC-1.1: Name Normalization
        try:
            assert clean_hotel_title("AMC Royal Hotel & Spa (ex. AMC Azur Resort)") == "AMC Royal Hotel & Spa"
            assert clean_hotel_title("Delphin Imperial (Lara)") == "Delphin Imperial"
            assert clean_hotel_title("Rixos Premium Hotel Belek 5*") == "Rixos Premium Hotel Belek"
            assert slugify_hotel_name("Rixos Premium Belek (ex. Troy)") == "rixos-premium-belek"
            self.record_result("TC-1.1", "Normalization & Slugification strips ex-names, stars, and geo tags", True)
        except Exception as e:
            self.record_result("TC-1.1", "Normalization & Slugification strips ex-names, stars, and geo tags", False, str(e))

        # TC-1.2: Chain Sub-Property Deduplication
        try:
            reg = HotelCanonicalRegistry()
            h1 = reg.register_hotel("Pickalbatros Aqua Blu Resort", destination="Египет")
            h2 = reg.register_hotel("Pickalbatros Laguna Club Resort", destination="Египет")
            assert h1["slug"] != h2["slug"], f"Conflated sub-properties: {h1['slug']} == {h2['slug']}"

            h_var = reg.register_hotel("Pickalbatros Aqua Blu Resort (ex. Sea World)", destination="Египет")
            assert h_var["slug"] == h1["slug"], "Failed to match legitimate ex-name variant"
            self.record_result("TC-1.2", "Two-Phase Deduplication preserves distinct sub-properties of same brand", True)
        except Exception as e:
            self.record_result("TC-1.2", "Two-Phase Deduplication preserves distinct sub-properties of same brand", False, str(e))

        # TC-1.3: Package Composition Extraction (No fake '2 adults')
        try:
            cfg_2p1 = {"url": "https://fly.pl/szukaj/?adults=2&children=10-12-2020", "subtitle": "2+1"}
            comp_2p1 = extract_package_composition(cfg_2p1)
            assert comp_2p1["adults"] == 2 and comp_2p1["children"] == 1
            assert comp_2p1["label"] == "2 взр. + 1 реб."

            cfg_1p = {"url": "https://fly.pl/szukaj/?filter[person]=1&filter[child]=0", "subtitle": "1 взр"}
            comp_1p = extract_package_composition(cfg_1p)
            assert comp_1p["adults"] == 1 and comp_1p["children"] == 0
            assert comp_1p["label"] == "1 взр."

            self.record_result("TC-1.3", "Accurate Package Composition extraction (2+1, 1 adult, 2 adults)", True)
        except Exception as e:
            self.record_result("TC-1.3", "Accurate Package Composition extraction (2+1, 1 adult, 2 adults)", False, str(e))

        # TC-1.4: Strict Confidence Level & Anti-Fabrication
        try:
            hotels, stats = collect_hotel_data()
            assert len(hotels) > 0, "No hotels generated by aggregator"

            low_conf_hotels = [h for h in hotels if h["confidence_level"] == "low"]
            high_conf_hotels = [h for h in hotels if h["confidence_level"] == "high"]

            # Rule: Low confidence hotels must NOT display archetype or canned verdict
            for h in low_conf_hotels:
                assert h["archetype"] is None, f"Low confidence hotel {h['hotel_name']} has fabricated archetype {h['archetype']}"
                if h["verdict"]:
                    assert "песчано-галечный" not in h["verdict"].lower(), f"Low confidence hotel has canned verdict: {h['verdict']}"

            self.record_result("TC-1.4", "Strict confidence scoring prevents fabricated archetypes on low-sample hotels", True, f"High: {len(high_conf_hotels)}, Low: {len(low_conf_hotels)}")
        except Exception as e:
            self.record_result("TC-1.4", "Strict confidence scoring prevents fabricated archetypes on low-sample hotels", False, str(e))

        # TC-1.5: Anti-Template & Schema Validation
        try:
            # Valid payload
            valid_spec = {
                "beach_type": "sand",
                "beach_line": 1,
                "sea_entry": "shallow_sand",
                "tripadvisor_rating": 4.5,
                "highlights": ["Отличный пляж", "Свежий ремонт"],
            }
            ok, err = validate_specs_payload(valid_spec)
            assert ok and err is None
            assert not is_template_response(valid_spec)

            # Invalid beach_type
            invalid_spec = {"beach_type": "super_rocky_custom"}
            ok, err = validate_specs_payload(invalid_spec)
            assert not ok

            # Canned response
            canned_spec = {
                "beach_type": "sand",
                "highlights": ["Песчано-галечный пляж с удобным входом в море"],
            }
            assert is_template_response(canned_spec)
            self.record_result("TC-1.5", "Anti-template detector and schema validator catch invalid/canned responses", True)
        except Exception as e:
            self.record_result("TC-1.5", "Anti-template detector and schema validator catch invalid/canned responses", False, str(e))

    # ==========================================
    # SUITE 2: UI & BROWSER INTERACTION (PLAYWRIGHT)
    # ==========================================
    def run_suite_2_ui_e2e(self):
        print("\n--- Running Suite 2: UI & Browser Interaction (Playwright) ---")
        page_errors = []
        console_errors = []

        with sync_playwright() as p:
            browser = p.chromium.launch(headless=True)
            context = browser.new_context(viewport={"width": 1440, "height": 900})
            page = context.new_page()

            page.on("pageerror", lambda err: page_errors.append(str(err)))
            page.on("console", lambda msg: console_errors.append(msg.text) if msg.type == "error" else None)

            # TC-2.1: Page Structure & Meta
            try:
                target_url = f"{self.base_url}/hotels.html"
                page.goto(target_url, wait_until="networkidle")
                page.wait_for_timeout(500)

                title = page.title()
                assert "Каталог отелей" in title, f"Unexpected page title: {title}"
                kpi_hotels = page.locator("#kpiTotalHotels").text_content()
                assert int(kpi_hotels) > 50, f"KPI total hotels too low: {kpi_hotels}"
                self.record_result("TC-2.1", "Page header, KPIs, and meta tags load correctly", True, f"Hotels displayed: {kpi_hotels}")
            except Exception as e:
                self.record_result("TC-2.1", "Page header, KPIs, and meta tags load correctly", False, str(e))

            # TC-2.2: Instant Search Functionality
            try:
                search_input = page.locator("#searchInput")
                search_input.fill("Rixos")
                page.wait_for_timeout(300)

                cards = page.locator(".hotel-card")
                count = cards.count()
                assert count > 0, "No cards found for 'Rixos'"
                for idx in range(min(count, 3)):
                    text = cards.nth(idx).locator(".card-title").text_content()
                    assert "rixos" in text.lower(), f"Card title does not match search query: {text}"

                # Test empty state
                search_input.fill("xyzNonExistentHotel12345")
                page.wait_for_timeout(300)
                empty_state = page.locator(".empty-state")
                assert empty_state.count() == 1, "Empty state not displayed on zero results"

                # Reset search
                search_input.fill("")
                page.wait_for_timeout(300)
                self.record_result("TC-2.2", "Search bar with debounce and empty-state works smoothly", True, f"Found {count} Rixos hotels")
            except Exception as e:
                self.record_result("TC-2.2", "Search bar with debounce and empty-state works smoothly", False, str(e))

            # TC-2.3: Country Filter Chips
            try:
                # Click Cyprus chip
                cyprus_chip = page.locator('#countryChips .chip[data-country="Кипр"]')
                cyprus_chip.click()
                page.wait_for_timeout(300)

                cards = page.locator(".hotel-card")
                count_cyprus = cards.count()
                assert count_cyprus > 0, "Zero Cyprus hotels displayed"
                for idx in range(min(count_cyprus, 3)):
                    badge = cards.nth(idx).locator(".badge-country").text_content()
                    assert badge == "Кипр", f"Expected 'Кипр' badge, got: {badge}"

                # Click Egypt chip
                page.locator('#countryChips .chip[data-country="Египет"]').click()
                page.wait_for_timeout(300)
                count_egypt = page.locator(".hotel-card").count()
                assert count_egypt > 0, "Zero Egypt hotels displayed"

                # Reset to All
                page.locator('#countryChips .chip[data-country="all"]').click()
                page.wait_for_timeout(300)
                self.record_result("TC-2.3", "Country filter chips filter cards accurately", True, f"Cyprus: {count_cyprus}, Egypt: {count_egypt}")
            except Exception as e:
                self.record_result("TC-2.3", "Country filter chips filter cards accurately", False, str(e))

            # TC-2.4: Smart Collection Chips
            try:
                # Click Flash Drops chip
                drops_chip = page.locator('#collectionChips .chip[data-collection="flash_drops"]')
                drops_chip.click()
                page.wait_for_timeout(300)
                drops_count = page.locator(".hotel-card").count()
                assert drops_count > 0, "Zero flash drop hotels found"

                for idx in range(min(drops_count, 3)):
                    drop_badge = page.locator(".hotel-card").nth(idx).locator(".badge-drop")
                    assert drop_badge.count() == 1, "Hotel card missing discount badge"

                # Toggle chip off
                drops_chip.click()
                page.wait_for_timeout(300)
                self.record_result("TC-2.4", "Smart collections chips filter cards and toggle off", True, f"Flash drops count: {drops_count}")
            except Exception as e:
                self.record_result("TC-2.4", "Smart collections chips filter cards and toggle off", False, str(e))

            # TC-2.5: Sort Ordering
            try:
                sort_select = page.locator("#sortSelect")
                sort_select.select_option("price_asc")
                page.wait_for_timeout(300)

                prices = []
                cards = page.locator(".hotel-card")
                for idx in range(min(cards.count(), 5)):
                    p_text = cards.nth(idx).locator(".price-main").text_content()
                    val = float(re.sub(r"[^\d.]", "", p_text))
                    prices.append(val)

                assert prices == sorted(prices), f"Prices not ascending: {prices}"
                self.record_result("TC-2.5", "Sort selector sorts hotels in ascending price order", True, f"First 5 prices: {prices}")
            except Exception as e:
                self.record_result("TC-2.5", "Sort selector sorts hotels in ascending price order", False, str(e))

            # TC-2.6: Hotel Passport Drawer Opening
            try:
                first_card = page.locator(".hotel-card").first
                card_title = first_card.locator(".card-title").text_content().strip()
                first_card.click()
                page.wait_for_timeout(500)

                drawer = page.locator("#passportDrawer")
                assert "open" in drawer.get_attribute("class"), "Drawer did not open"
                drawer_title = page.locator("#drawerHotelTitle").text_content().strip()
                assert card_title == drawer_title, f"Drawer title '{drawer_title}' != card title '{card_title}'"

                # Check hero stats pills
                pills = page.locator("#drawerHeroStats .stat-pill")
                assert pills.count() >= 3, f"Insufficient stat pills in hero: {pills.count()}"
                self.record_result("TC-2.6", "Clicking hotel card opens Slide-Over Drawer with matching hotel passport", True, f"Hotel: {card_title}")
            except Exception as e:
                self.record_result("TC-2.6", "Clicking hotel card opens Slide-Over Drawer with matching hotel passport", False, str(e))

            # TC-2.7: Passport Tabs Navigation & Plotly Chart
            try:
                # Tab 2: Packages
                page.locator('.tab-btn[data-tab="packages"]').click()
                page.wait_for_timeout(300)
                pane_pkg = page.locator("#panePackages")
                assert "active" in pane_pkg.get_attribute("class")
                tbody_rows = page.locator("#drawerPackagesTbody tr").count()
                assert tbody_rows > 0, "No package rows in table"

                # Tab 3: Infrastructure
                page.locator('.tab-btn[data-tab="infra"]').click()
                page.wait_for_timeout(300)
                pane_infra = page.locator("#paneInfra")
                assert "active" in pane_infra.get_attribute("class")

                # Tab 4: Monitoring Coverage
                page.locator('.tab-btn[data-tab="monitoring"]').click()
                page.wait_for_timeout(300)
                pane_mon = page.locator("#paneMonitoring")
                assert "active" in pane_mon.get_attribute("class")

                # Tab 1: History & Plotly
                page.locator('.tab-btn[data-tab="history"]').click()
                page.wait_for_timeout(600)
                chart_plot = page.locator("#hotelPlotlyChart .plot-container")
                assert chart_plot.count() > 0, "Plotly chart container missing"
                self.record_result("TC-2.7", "All 4 passport tabs switch seamlessly and Plotly chart renders without errors", True)
            except Exception as e:
                self.record_result("TC-2.7", "All 4 passport tabs switch seamlessly and Plotly chart renders without errors", False, str(e))

            # TC-2.8: Deep-linking via Hash URL
            try:
                page.locator("#drawerCloseBtn").click()
                page.wait_for_timeout(300)

                # Test deep link to Cyprus hotel
                page.goto(f"{self.base_url}/hotels.html#acapulco-resort", wait_until="networkidle")
                page.wait_for_timeout(800)

                drawer = page.locator("#passportDrawer")
                assert "open" in drawer.get_attribute("class"), "Drawer did not open from deep-link"
                title = page.locator("#drawerHotelTitle").text_content()
                assert "Acapulco" in title, f"Deep link opened wrong hotel: {title}"

                # Test closing drawer resets hash
                page.locator("#drawerCloseBtn").click()
                page.wait_for_timeout(300)
                assert "open" not in drawer.get_attribute("class")
                self.record_result("TC-2.8", "Deep-linking via URL hash opens specific hotel passport directly", True, f"Opened: {title}")
            except Exception as e:
                self.record_result("TC-2.8", "Deep-linking via URL hash opens specific hotel passport directly", False, str(e))

            # TC-2.9: Console & Runtime Errors Inspection
            try:
                assert len(page_errors) == 0, f"Page errors encountered: {page_errors}"
                assert len(console_errors) == 0, f"Console error logs: {console_errors}"
                self.record_result("TC-2.9", "Zero console or runtime errors during complete interactive E2E session", True, "0 PAGE ERROR")
            except Exception as e:
                self.record_result("TC-2.9", "Zero console or runtime errors during complete interactive E2E session", False, str(e))

            browser.close()

    # ==========================================
    # SUITE 3: INTEGRATION & WORKFLOW CHECKS
    # ==========================================
    def run_suite_3_integration(self):
        print("\n--- Running Suite 3: Ecosystem Integration & Git Safety ---")

        # TC-3.1: Landing Page Button
        try:
            landing_code = (ROOT / "generate_landing.py").read_text(encoding="utf-8")
            assert 'href="hotels.html"' in landing_code
            assert "Каталог отелей" in landing_code
            self.record_result("TC-3.1", "Landing page includes Hotel Catalog navigation button", True)
        except Exception as e:
            self.record_result("TC-3.1", "Landing page includes Hotel Catalog navigation button", False, str(e))

        # TC-3.2: Dashboard Sidebar Link
        try:
            dash_code = (ROOT / "generate_inline_charts_dashboard.py").read_text(encoding="utf-8")
            assert 'href="hotels.html"' in dash_code
            assert "Каталог отелей" in dash_code
            self.record_result("TC-3.2", "Dashboard sidebar template includes Hotel Catalog link", True)
        except Exception as e:
            self.record_result("TC-3.2", "Dashboard sidebar template includes Hotel Catalog link", False, str(e))

        # TC-3.3: Site Bundle Packaging
        try:
            pages_sh = (ROOT / "scripts/prepare_pages_site.sh").read_text(encoding="utf-8")
            assert "hotels.html" in pages_sh
            assert "hotels_catalog_data.json" in pages_sh
            self.record_result("TC-3.3", "prepare_pages_site.sh packages catalog files into site/ bundle", True)
        except Exception as e:
            self.record_result("TC-3.3", "prepare_pages_site.sh packages catalog files into site/ bundle", False, str(e))

        # TC-3.4: Git Safety & .gitignore
        try:
            gitignore = (ROOT / ".gitignore").read_text(encoding="utf-8")
            assert "hotels.html" in gitignore
            assert "hotels_catalog_data.json" in gitignore
            assert "!test_hotel_*.py" in gitignore
            self.record_result("TC-3.4", ".gitignore correctly protects generated catalog files from accidental commits", True)
        except Exception as e:
            self.record_result("TC-3.4", ".gitignore correctly protects generated catalog files from accidental commits", False, str(e))

    def run_all(self):
        self.run_suite_1_data_integrity()
        self.run_suite_2_ui_e2e()
        self.run_suite_3_integration()

        total = len(self.results)
        passed = sum(1 for r in self.results if r["passed"])
        failed = sum(1 for r in self.results if not r["passed"])

        print(f"\n==========================================")
        print(f"📊 QA TEST RUN COMPLETE: {passed}/{total} PASSED ({failed} FAILED)")
        print(f"==========================================")
        return self.results, self.bugs_found


if __name__ == "__main__":
    runner = ComprehensiveCatalogQARunner()
    results, bugs = runner.run_all()
    if bugs:
        sys.exit(1)
